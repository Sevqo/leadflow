test('lead filters, bulk actions and recoverable archive work', async ({ page }) => {
  await page.locator('.sidebar nav').getByRole('button', { name: 'Leads' }).click()
  await page.getByLabel('Filter by stage').selectOption('New')
  await expect(page.locator('.crm-leads-table tbody tr')).toHaveCount(1)
  await page.getByLabel('Select Brian Otieno').check()
  await page.getByRole('button', { name: 'Mark qualified' }).click()
  await expect(page.locator('.crm-empty')).toContainText('No matching leads')
  await page.getByLabel('Filter by stage').selectOption('Qualified')
  await page.getByLabel('Select Brian Otieno').check()
  await page.getByRole('button', { name: 'Archive' }).click()
  await expect(page.locator('.crm-leads-table tbody')).not.toContainText('Brian Otieno')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('nexara-demo-workspace-v2')!))
  expect(saved.leads.find((lead: { id: string }) => lead.id === 'lead-brian').archived).toBe(true)
})

