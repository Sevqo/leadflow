test('creates a complete lead, opens its profile and persists it after reload', async ({ page }) => {
  await page.locator('.sidebar nav').getByRole('button', { name: 'Leads' }).click()
  await page.getByRole('button', { name: 'Add lead' }).click()
  const dialog = page.getByRole('dialog', { name: 'Add a lead' })
  await dialog.getByLabel('Full name').fill('Grace Wambui')
  await dialog.getByLabel('Interest').fill('Commercial office · Upper Hill')
  await dialog.getByLabel('Email', { exact: true }).fill('grace@example.com')
  await dialog.getByLabel('Phone').fill('+254 700 111 222')
  await dialog.getByLabel('Company').fill('Wambui Studio')
  await dialog.getByLabel('Budget / value').fill('KSh 35M')
  await dialog.getByLabel('Source').selectOption('Referral')
  await dialog.getByLabel('Owner').selectOption('Sarah')
  await dialog.getByLabel('Stage').selectOption('Qualified')
  await dialog.getByLabel('Lead score').fill('91')
  await dialog.getByLabel('Next action').fill('Arrange site visit')
  await dialog.getByLabel(/Tags/).fill('High intent, Office')
  await dialog.getByLabel(/Custom fields/).fill('Preferred floor: 8th\nParking bays: 2')
  await dialog.getByRole('button', { name: 'Create lead' }).click()
  const profile = page.getByRole('dialog').filter({ hasText: 'Grace Wambui' })
  await expect(profile).toContainText('Commercial office · Upper Hill')
  await expect(profile).toContainText('91/100')
  await expect(profile).toContainText('Preferred floor')
  await expect(profile).toContainText('8th')
  await profile.getByRole('button', { name: 'Close profile' }).click()
  await page.reload()
  await page.locator('.sidebar nav').getByRole('button', { name: 'Leads' }).click()
  await page.getByLabel('Search leads').fill('Grace')
  await expect(page.locator('.crm-leads-table tbody')).toContainText('Grace Wambui')
  await expect(page.locator('.crm-leads-table tbody')).toContainText('KSh 35M')
  await page.getByRole('button',{name:'Grace Wambui'}).click()
  await expect(page.getByRole('dialog')).toContainText('Parking bays')
})

